export const POPULAR_TITLES = ROLE_EXAMPLES.map((r) => r.title);

/** Best matching built-in role for a job title, or null. */
export function findRoleExamples(jobTitle = '') {
  const q = jobTitle.toLowerCase().trim();
  if (!q) return null;
  const exact = ROLE_EXAMPLES.find((r) => r.title.toLowerCase() === q);
  if (exact) return exact;
  let best = null;
  let score = 0;
  ROLE_EXAMPLES.forEach((r) => {
    const s = r.keywords.reduce((n, k) => n + (q.includes(k) ? k.length : 0), 0) + (r.title.toLowerCase().includes(q) ? 5 : 0);
    if (s > score) {
      score = s;
      best = r;
    }
  });
  return best;
}

